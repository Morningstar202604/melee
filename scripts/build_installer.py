#!/usr/bin/env python
"""构建 Windows 安装器（Inno Setup）：dist/melee → melee-setup-<ver>-win64.exe。

用法：
    .venv/Scripts/python.exe scripts/build_installer.py            # 编译安装器
    .venv/Scripts/python.exe scripts/build_installer.py --check    # 只校验模板（门禁用）

为什么单独一个脚本：PyInstaller 产物大约要几分钟，而安装器只是把 dist/melee
装进一个向导。两步分开后，改安装器不用重跑 PyInstaller；门禁只跑 --check，
完整安装-运行-卸载链路在发布流程里跑一次。

为什么默认装到 {localappdata}：PrivilegesRequired=lowest，不需要管理员权限、
不弹 UAC；卸载只清理安装目录，不碰用户数据目录。
占位符用 @NAME@：Inno 自己的常量是 {app} 这类花括号写法，混用会互相替换出错。
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"

APP_VERSION = "1.9.0"

ISS_TEMPLATE = r"""; melee installer script — generated by scripts/build_installer.py
; Per-user install: no UAC prompt, no admin needed, uninstall touches only its own dir.

[Setup]
AppId={{6F2C1E4A-9D3B-4C5E-8A17-B2D0F84C1E90}
AppName=melee
AppVersion=@VERSION@
AppVerName=melee @VERSION@
AppPublisher=melee contributors
DefaultDirName={localappdata}\Programs\melee
DisableProgramGroupPage=yes
Uninstallable=yes
CreateAppDir=yes
OutputDir=@OUTPUT@
OutputBaseFilename=melee-setup-@VERSION@-win64
@ICON_LINE@PrivilegesRequired=lowest
Compression=lzma2/max
SolidCompression=yes
ArchitecturesInstallIn64BitMode=x64compatible
CloseApplications=yes
RestartApplications=no
UninstallDisplayName=melee @VERSION@
UninstallDisplayIcon={app}\melee.exe

[Files]
Source: "@ROOT@\dist\melee\*"; DestDir: "{app}"; Flags: recursesubdirs createallsubdirs ignoreversion

[Icons]
Name: "{userprograms}\melee"; Filename: "{app}\melee.exe"; Comment: "melee broadcast studio (CLI + service)"
Name: "{userprograms}\melee (start service)"; Filename: "{app}\start.bat"; Comment: "Serve melee on http://127.0.0.1:8099"

[Run]
Filename: "{app}\melee.exe"; Parameters: "--version"; Description: "Verify the install (runs melee --version)"; Flags: postinstall skipifsilent runasoriginaluser

[Messages]
WelcomeLabel1=melee @VERSION@ — self-hosted broadcast studio for AI matches

[UninstallDelete]
; 安装目录里的运行时数据随卸载删除；用户数据目录（%LOCALAPPDATA%\melee\data）保留。
Type: filesandordirs; Name: "{app}\data"
"""

REQUIRED_DIRECTIVES = [
    "PrivilegesRequired=lowest",
    "DefaultDirName={localappdata}",
    "Uninstallable=yes",
    "OutputBaseFilename=melee-setup-",
]


def render_iss(output_dir: Path) -> str:
    """渲染 .iss。icon 缺失时省略 SetupIconFile，保持脚本在无图标环境也能跑。"""
    icon = ROOT / "apps" / "web" / "favicon.ico"
    subs = {
        "VERSION": APP_VERSION,
        "OUTPUT": str(output_dir),
        "ROOT": str(ROOT),
    }
    text = ISS_TEMPLATE.replace("@ICON_LINE@", f"SetupIconFile={icon}\n" if icon.exists() else "")
    for key, value in subs.items():
        text = text.replace(f"@{key}@", value)
    leftovers = re.findall(r"@[A-Z_]+@", text)
    if leftovers:
        raise RuntimeError(f"iss 模板还有未替换的占位符：{sorted(set(leftovers))}")
    return text


def check() -> int:
    """门禁：模板必须能渲染、必须含关键指令、版本必须与 CHANGELOG 同步。"""
    text = render_iss(DIST)
    for directive in REQUIRED_DIRECTIVES:
        if directive not in text:
            print(f"FAIL 安装器模板缺少关键指令：{directive}", file=sys.stderr)
            return 1
    if f"AppVersion={APP_VERSION}" not in text:
        print(f"FAIL 安装器版本 {APP_VERSION} 与代码不同步", file=sys.stderr)
        return 1
    # 版本必须与 CHANGELOG 顶部一致（与 test_architecture 的四处载体同源）
    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    expected = re.search(r"^## \[(\d+\.\d+\.\d+)\]", changelog, re.MULTILINE)
    if not expected or expected.group(1) != APP_VERSION:
        print(f"FAIL build_installer APP_VERSION={APP_VERSION} 与 CHANGELOG 顶部不同步", file=sys.stderr)
        return 1
    if "dist\\melee\\*" not in text.replace("/", "\\"):
        print("FAIL 安装器必须打包 dist/melee 全目录", file=sys.stderr)
        return 1
    print(f"installer template ok (v{APP_VERSION})")
    return 0


def compile_installer() -> int:
    out_dir = DIST
    out_dir.mkdir(exist_ok=True)
    iss = out_dir / "melee-installer.iss"
    iss.write_text(render_iss(out_dir), encoding="utf-8")

    iscc_candidates = [
        Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
        Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
    ]
    iscc = next((p for p in iscc_candidates if p.exists()), None)
    if iscc is None:
        print("FAIL 未找到 Inno Setup 6（ISCC.exe）。安装：choco install innosetup -y", file=sys.stderr)
        return 2

    result = subprocess.run([str(iscc), str(iss)], capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stdout[-2000:], file=sys.stderr)
        print(result.stderr[-2000:], file=sys.stderr)
        return 1

    setup = DIST / f"melee-setup-{APP_VERSION}-win64.exe"
    if not setup.exists():
        print("FAIL 编译成功但没找到输出文件", file=sys.stderr)
        return 1
    print(f"OK: {setup.name} ({setup.stat().st_size / 1_000_000:.0f} MB)")
    return 0


def main() -> int:
    return check() if "--check" in sys.argv else compile_installer()


if __name__ == "__main__":
    raise SystemExit(main())
