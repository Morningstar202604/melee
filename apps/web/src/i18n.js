export const LANGS = ['en', 'zh']
export const DEFAULT_LANG = 'en'
const STORAGE_KEY = 'melee.lang'

let current = DEFAULT_LANG

/** 解析生效语言：URL ?lang= 优先，其次用户上次的选择，再次浏览器语言，最后英文。
 *
 * 浏览器语言这一层是必需的：产品默认英文，但中文用户打开链接时
 * 应该先看到中文。只有显式 `?lang=` 或切换过的选择才覆盖它。
 */
export function resolveLang(search = location.search) {
  const fromQuery = new URLSearchParams(search).get('lang')
  if (fromQuery && LANGS.includes(fromQuery)) return fromQuery
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored && LANGS.includes(stored)) return stored
  } catch {
    /* 隐私模式下 localStorage 会抛，静默降级到默认语言 */
  }
  // navigator.languages 是用户偏好顺序；任一以 zh 开头就选中文。
  const preferred = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || '']
  for (const tag of preferred) {
    const primary = String(tag).toLowerCase().split('-')[0]
    if (LANGS.includes(primary)) return primary
  }
  return DEFAULT_LANG
}

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : DEFAULT_LANG
  try {
    localStorage.setItem(STORAGE_KEY, current)
  } catch {
    /* 存不下就只影响本次会话，不阻断渲染 */
  }
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en'
  return current
}

export function getLang() {
  return current
}

/**
 * 取文案。缺失时返回键名本身，让漏翻在界面上显形。
 * @param {string} key 形如 `home.hero.title`
 * @param {Record<string, string|number>} [params] `{name}` 占位符的取值
 */
export function t(key, params) {
  const table = DICT[current] || DICT[DEFAULT_LANG]
  let text = table[key]
  if (text === undefined) text = DICT[DEFAULT_LANG][key]
  if (text === undefined) return key
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  )
}

/** 赛制名走字典；未登记的新赛制回退到服务端给的原始 label。 */
export function gameLabel(gameId, fallback = '') {
  const key = `game.${gameId}`
  const text = t(key)
  return text === key ? fallback || gameId : text
}

/** 把 data-i18n / data-i18n-attr 标注的静态节点刷成当前语言。 */
export function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    const key = node.dataset.i18n
    const value = t(key)
    if (node.dataset.i18nHtml === 'true') node.innerHTML = value
    else node.textContent = value
  }
  for (const node of root.querySelectorAll('[data-i18n-attr]')) {
    // 格式：data-i18n-attr="placeholder:home.library.search|aria-label:home.library.searchLabel"
    for (const pair of node.dataset.i18nAttr.split('|')) {
      const [attr, key] = pair.split(':')
      if (attr && key) node.setAttribute(attr.trim(), t(key.trim()))
    }
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.setAttribute('title', t(node.dataset.i18nTitle))
  }
}
